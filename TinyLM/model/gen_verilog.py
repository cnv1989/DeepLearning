"""Turn trained weights into hard-wired Verilog.

Writes into rtl/generated/:
  tinylm_params.vh          localparams included inside the hand-written modules
  tinylm_weights.v          weight/bias/embedding ROMs as `case` statements
                            (the weights become logic gates -- nothing is loaded at run time)
  tinylm_charmap.v          ASCII <-> token conversion
  tinylm_core_parallel.v    fully-parallel core: every weight is a wire, one token per clock

Usage: python3 model/gen_verilog.py --weights model/weights/tt.json
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import charset  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = "// AUTO-GENERATED by model/gen_verilog.py -- do not edit by hand.\n"


def clog2(n):
    return max(1, (n - 1).bit_length())


def tern_bits(w):
    return {0: "2'b00", 1: "2'b01", -1: "2'b11"}[w]


def check_ranges(w, c):
    """Prove the accumulators can never overflow (worst case over all inputs)."""
    emax = (1 << (c["E_BITS"] - 1)) - 1
    hmax = (1 << c["H_BITS"]) - 1
    lim = (1 << (c["ACC_W"] - 1)) - 1
    for j in range(c["H"]):
        worst = abs(w["b1"][j]) + sum(abs(v) for v in w["W1"][j]) * (emax + 1)
        assert worst <= lim, f"layer-1 neuron {j} may overflow ACC_W"
    for k in range(c["V"]):
        worst = abs(w["b2"][k]) + sum(abs(v) for v in w["W2"][k]) * hmax + (1 << c["NOISE_BITS"])
        assert worst <= lim, f"layer-2 logit {k} may overflow ACC_W"


def params_vh(c):
    p = {
        "N": c["N"], "D": c["D"], "LOG2D": clog2(c["D"]) if c["D"] > 1 else 1,
        "H": c["H"], "V": c["V"], "ND": c["ND"], "S1": c["S1"],
        "E_BITS": c["E_BITS"], "H_BITS": c["H_BITS"], "B_BITS": c["B_BITS"],
        "ACC_W": c["ACC_W"], "NOISE_BITS": c["NOISE_BITS"],
        "P_W": clog2(c["N"]), "J_W": clog2(c["H"]), "K_W": clog2(c["V"]),
        "W1_AW": clog2(c["H"] * c["ND"]), "W2_AW": clog2(c["V"] * c["H"]),
    }
    s = HEADER + f"// config '{c['name']}'\n"
    s += "".join(f"localparam integer {k:<10} = {v};\n" for k, v in p.items())
    return s


def rom(name, aw, dw, entries, signed, comment):
    """entries: dict addr -> int. Zero entries are left to `default`."""
    s = f"// {comment}\nmodule {name} (\n    input  wire [{aw-1}:0] addr,\n"
    s += f"    output reg  {'signed ' if signed else ''}[{dw-1}:0] data\n);\n"
    s += "    always @* begin\n        case (addr)\n"
    for a, v in sorted(entries.items()):
        if v == 0:
            continue
        lit = (f"-{dw}'sd{-v}" if v < 0 else f"{dw}'sd{v}") if signed else (tern_bits(v) if dw == 2 else f"{dw}'d{v}")
        s += f"            {aw}'d{a}: data = {lit};\n"
    s += f"            default: data = {dw}'d0;\n        endcase\n    end\nendmodule\n\n"
    return s


def weights_v(w, c):
    D, ND, H, V = c["D"], c["ND"], c["H"], c["V"]
    logd = clog2(D) if D > 1 else 1
    s = HEADER + "// Ternary weights use 2 bits: 00 = 0, 01 = +1, 11 = -1\n\n"
    emb = {(t << logd) | d: w["E"][t][d] for t in range(V) for d in range(D)}
    s += rom("tinylm_emb_rom", 5 + logd, c["E_BITS"], emb, True,
             "Embedding table E[token][d], address = {token, d}")
    s += rom("tinylm_w1_rom", clog2(H * ND), 2,
             {j * ND + i: w["W1"][j][i] for j in range(H) for i in range(ND)}, False,
             "Layer-1 ternary weights W1[j][i], address = j*ND + i")
    s += rom("tinylm_b1_rom", clog2(H), c["B_BITS"], dict(enumerate(w["b1"])), True, "Layer-1 biases")
    s += rom("tinylm_w2_rom", clog2(V * H), 2,
             {k * H + j: w["W2"][k][j] for k in range(V) for j in range(H)}, False,
             "Layer-2 ternary weights W2[k][j], address = k*H + j")
    s += rom("tinylm_b2_rom", clog2(V), c["B_BITS"], dict(enumerate(w["b2"])), True, "Layer-2 biases")
    return s


def charmap_v():
    s = HEADER + "// Token -> ASCII\nmodule tinylm_tok2char (input wire [4:0] tok, output reg [7:0] ch);\n"
    s += "    always @* begin\n        case (tok)\n"
    for i, ch in enumerate(charset.CHARS):
        s += f"            5'd{i}: ch = 8'h{ord(ch):02x};  // {ch!r}\n"
    s += "            default: ch = 8'h20;\n        endcase\n    end\nendmodule\n\n"
    s += "// ASCII -> token (upper case folds to lower case, unknown -> space)\n"
    s += "module tinylm_char2tok (input wire [7:0] ch, output reg [4:0] tok);\n"
    s += "    always @* begin\n        if (ch >= 8'h61 && ch <= 8'h7a)      tok = ch - 8'h60;  // a-z\n"
    s += "        else if (ch >= 8'h41 && ch <= 8'h5a) tok = ch - 8'h40;  // A-Z\n"
    s += "        else begin\n            case (ch)\n"
    for i, ch in enumerate(charset.CHARS):
        if not ch.isalpha() and i != 0:
            s += f"                8'h{ord(ch):02x}: tok = 5'd{i};  // {ch!r}\n"
    s += "                default: tok = 5'd0;\n            endcase\n        end\n    end\nendmodule\n"
    return s


def parallel_core_v(w, c):
    """Fully-unrolled datapath. Ternary weights mean every 'multiply' is just
    +x, -x or nothing, so each neuron is an adder tree of the wires it uses."""
    N, D, H, V, A = c["N"], c["D"], c["H"], c["V"], c["ACC_W"]
    logd = clog2(D) if D > 1 else 1
    eb, hb, nb = c["E_BITS"], c["H_BITS"], c["NOISE_BITS"]
    s = HEADER + """// Fully-parallel ("hard-wired") TinyLM core. Same ports and behaviour as
// rtl/tinylm_core.v, but the whole network is one combinational cloud:
// start -> done in a single clock cycle.
module tinylm_core_parallel (
    input  wire       clk,
    input  wire       rst_n,
    input  wire       push,
    input  wire [4:0] token_in,
    input  wire       start,
    input  wire       noise_en,
    output reg        busy,
    output reg        done,
    output reg  [4:0] token_out
);
`include "tinylm_params.vh"

    reg [N*5-1:0] ctx;
    reg [15:0]    lfsr;

    // ---------------- embeddings (N*D small ROMs) ----------------
"""
    for p in range(N):
        for d in range(D):
            s += (f"    wire signed [{eb-1}:0] e_{p}_{d};\n"
                  f"    tinylm_emb_rom u_e_{p}_{d} (.addr({{ctx[{p*5+4}:{p*5}], {logd}'d{d}}}), .data(e_{p}_{d}));\n"
                  f"    wire signed [{A-1}:0] x{p*D+d} = e_{p}_{d};\n")
    s += "\n    // ---------------- layer 1: adder trees + ReLU + requantise ----------------\n"
    for j in range(H):
        terms = [("+ " if v > 0 else "- ") + f"x{i}" for i, v in enumerate(w["W1"][j]) if v]
        b = w["b1"][j]
        s += f"    wire signed [{A-1}:0] a{j} = {A}'sd0 {'+' if b >= 0 else '-'} {A}'sd{abs(b)} {' '.join(terms)};\n"
        s += f"    wire [{hb-1}:0] h{j} = requant(a{j});\n"
    s += "\n    // ---------------- layer 2 + noise + argmax ----------------\n"
    s += "    wire [15:0] lf0 = lfsr;\n"
    for k in range(V):
        s += f"    wire [15:0] lf{k+1} = {{1'b0, lf{k}[15:1]}} ^ (lf{k}[0] ? 16'hB400 : 16'h0000);\n"
    for k in range(V):
        terms = [("+ " if v > 0 else "- ") + f"$signed({{{A-hb}'d0, h{j}}})" for j, v in enumerate(w["W2"][k]) if v]
        b = w["b2"][k]
        s += (f"    wire signed [{A-1}:0] z{k} = {A}'sd0 {'+' if b >= 0 else '-'} {A}'sd{abs(b)} {' '.join(terms)}"
              f" + (noise_en ? $signed({{{A-nb}'d0, lf{k}[{nb-1}:0]}}) : {A}'sd0);\n")
    # argmax as a chain (first maximum wins, like the sequential core)
    s += f"    wire signed [{A-1}:0] bv0 = z0;\n    wire [4:0] bi0 = 5'd0;\n"
    for k in range(1, V):
        s += (f"    wire signed [{A-1}:0] bv{k} = (z{k} > bv{k-1}) ? z{k} : bv{k-1};\n"
              f"    wire [4:0] bi{k} = (z{k} > bv{k-1}) ? 5'd{k} : bi{k-1};\n")
    s += f"""
    function [H_BITS-1:0] requant(input signed [ACC_W-1:0] a);
        reg signed [ACC_W-1:0] r;
        begin
            r = (a + (1 <<< (S1 - 1))) >>> S1;
            if (a <= 0)                       requant = 0;
            else if (r > (1 << H_BITS) - 1)   requant = (1 << H_BITS) - 1;
            else                              requant = r[H_BITS-1:0];
        end
    endfunction

    always @(posedge clk) begin
        if (!rst_n) begin
            ctx       <= 0;
            lfsr      <= 16'hACE1;
            busy      <= 1'b0;
            done      <= 1'b0;
            token_out <= 5'd0;
        end else begin
            done <= 1'b0;
            if (start) begin
                token_out <= bi{V-1};
                ctx       <= {{bi{V-1}, ctx[N*5-1:5]}};
                lfsr      <= lf{V};
                done      <= 1'b1;
            end else if (push) begin
                ctx <= {{token_in, ctx[N*5-1:5]}};
            end
        end
    end
endmodule
"""
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", default=os.path.join(ROOT, "model", "weights", "tt.json"))
    ap.add_argument("--outdir", default=os.path.join(ROOT, "rtl", "generated"))
    args = ap.parse_args()
    with open(args.weights) as f:
        w = json.load(f)
    c = w["config"]
    check_ranges(w, c)
    os.makedirs(args.outdir, exist_ok=True)
    files = {
        "tinylm_params.vh": params_vh(c),
        "tinylm_weights.v": weights_v(w, c),
        "tinylm_charmap.v": charmap_v(),
        "tinylm_core_parallel.v": parallel_core_v(w, c),
    }
    for name, text in files.items():
        with open(os.path.join(args.outdir, name), "w") as f:
            f.write(text)
        print(f"wrote {os.path.join(args.outdir, name)}")


if __name__ == "__main__":
    main()
