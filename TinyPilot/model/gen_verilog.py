"""Weights -> Verilog ROMs, and closed-loop test vectors.

rtl/generated/pilot_params.vh   network shape, shifts, integrator limits
rtl/generated/pilot_weights.v   W1/b1/W2/b2 as hard-wired case-statement ROMs
tb/vectors/flight.hex           one SPI frame per control loop + expected motors,
                                recorded while the bit-exact model flies the
                                simulated quad (so the test covers real flight data)
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import pilot  # noqa: E402
import quad_sim as qs  # noqa: E402

HDR = "// AUTO-GENERATED by model/gen_verilog.py -- do not edit by hand.\n"
N_STEPS = 400


def clog2(n):
    return max(1, (n - 1).bit_length())


def rom(name, aw, dw, values, comment):
    s = f"// {comment}\nmodule {name} (\n    input  wire [{aw-1}:0] addr,\n    output reg  signed [{dw-1}:0] data\n);\n"
    s += "    always @* begin\n        case (addr)\n"
    for a, v in enumerate(values):
        if v:
            lit = f"-{dw}'sd{-v}" if v < 0 else f"{dw}'sd{v}"
            s += f"            {aw}'d{a}: data = {lit};\n"
    s += f"            default: data = {dw}'sd0;\n        endcase\n    end\nendmodule\n\n"
    return s


def check_ranges(w):
    c = w["config"]
    lim = (1 << (c["ACC_W"] - 1)) - 1
    for j in range(c["H"]):
        assert abs(w["b1"][j]) + sum(abs(v) for v in w["W1"][j]) * 128 <= lim
    for k in range(pilot.N_OUT):
        assert abs(w["b2"][k]) + sum(abs(v) for v in w["W2"][k]) * 255 <= lim


def main():
    w = json.load(open(os.path.join(HERE, "weights.json")))
    c = w["config"]
    check_ranges(w)
    gen = os.path.join(ROOT, "rtl", "generated")
    os.makedirs(gen, exist_ok=True)
    H = c["H"]
    params = {
        "N_IN": pilot.N_IN, "N_OUT": pilot.N_OUT, "H": H, "W_BITS": c["W_BITS"], "B_BITS": c["B_BITS"],
        "S1": c["S1"], "S2": c["S2"], "ACC_W": c["ACC_W"],
        "I_LIM_R": w["I_LIM"][0], "I_LIM_P": w["I_LIM"][1], "I_LIM_Y": w["I_LIM"][2],
        "THR_IRESET": w["THR_IRESET"],
        "IN_W": clog2(pilot.N_IN), "J_W": clog2(H), "K_W": clog2(pilot.N_OUT),
        "W1_AW": clog2(H * pilot.N_IN), "W2_AW": clog2(pilot.N_OUT * H),
    }
    with open(os.path.join(gen, "pilot_params.vh"), "w") as f:
        f.write(HDR + "".join(f"localparam integer {k:<10} = {v};\n" for k, v in params.items()))
    s = HDR
    s += rom("pilot_w1_rom", params["W1_AW"], c["W_BITS"], [v for row in w["W1"] for v in row],
             "Layer-1 weights W1[j][i], address = j*N_IN + i")
    s += rom("pilot_b1_rom", params["J_W"], c["B_BITS"], w["b1"], "Layer-1 biases")
    s += rom("pilot_w2_rom", params["W2_AW"], c["W_BITS"], [v for row in w["W2"] for v in row],
             "Layer-2 weights W2[k][j], address = k*H + j")
    s += rom("pilot_b2_rom", params["K_W"], c["B_BITS"], w["b2"], "Layer-2 biases")
    with open(os.path.join(gen, "pilot_weights.v"), "w") as f:
        f.write(s)

    # ---- closed-loop vectors: the bit-exact chip model flies the quad ----
    rng = np.random.default_rng(99)
    quad = qs.Quad(rng)
    sp, thr = qs.stick_trajectory(rng, N_STEPS)
    thr[:20] = 0.0                     # start disarmed: exercises the integrator reset
    chip = pilot.Chip(pilot.IntNet(w))
    lines = []

    def ctl(spf, gyrof, thrf):
        sp_i, g_i = pilot.to_int16(spf), pilot.to_int16(gyrof)
        t_u8 = pilot.sat(int(thrf * 255 + 0.5), 0, 255)
        m = chip.step(sp_i, g_i, t_u8)
        frame = b"".join(int(v).to_bytes(2, "big", signed=True) for v in sp_i + g_i) + bytes([t_u8])
        lines.append(frame.hex() + "".join(f"{x:02x}" for x in m))
        return np.array(m) / 255.0
    qs.fly(ctl, quad, sp, thr)
    vec = os.path.join(ROOT, "tb", "vectors")
    os.makedirs(vec, exist_ok=True)
    with open(os.path.join(vec, "flight.hex"), "w") as f:
        f.write("\n".join(lines) + "\n")     # 13 frame bytes + 4 motor bytes = 136 bits per line
    with open(os.path.join(vec, "flight_len.vh"), "w") as f:
        f.write(f"localparam integer FLIGHT_LEN = {len(lines)};\n")
    print(f"wrote rtl/generated/pilot_params.vh, pilot_weights.v, tb/vectors/flight.hex ({len(lines)} loops)")


if __name__ == "__main__":
    main()
